/** The records a view returned, flattened. A grouped view is still one table. */
export function rowsOf(outcome: ViewRead): RecordDoc[] {
  if (outcome.grouped && outcome.groups) return outcome.groups.flatMap((group) => group.records);
  return outcome.records ?? [];
}

/** The design's own rule: a label, else the key. The key is never hidden. */
export function labelOf(field: FieldRead | undefined, key: string): string {
  if (!field) return key;
  return field.label && field.label.length > 0 ? field.label : key;
}

/** A record's own label: `title`, else `label`, else `name`, else its id (Appendix C.1). */
export function recordLabel(record: RecordDoc): string {
  for (const key of ['title', 'label', 'name']) {
    const value = record.fields[key];
    if (typeof value === 'string' && value.length > 0) return value;
  }
  // A kind whose own name for a row is something else (`term` on a vocabulary
  // word, `code` on a course) still reads as words in a review queue or a
  // picker: the first non-empty string field is a better label than an id, and
  // the id remains the fallback when there is no text at all.
  for (const value of Object.values(record.fields)) {
    if (typeof value === 'string' && value.length > 0) return value;
  }
  return record.id;
}

/**
 * A key spoken as a name: `today.topics` reads as “Today Topics” when the plan
 * gave the thing no title of its own (D2: a dotted id never reaches a screen).
 */
export function nameOf(key: string): string {
  return key
    .replace(/[._-]+/g, ' ')
    .replace(/\b\w/g, (letter) => letter.toUpperCase())
    .trim();
}

