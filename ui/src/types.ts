/** `SAM views --json` — the bootstrap: what exists and where it is reached from. */
export type ViewsRead = {
  views: Record<string, ViewDefRead>;
  navigation: Array<{ title: string; view: string; icon?: string | null }>;
  types: Record<string, TypeRead>;
  keybindings: KeybindingRead[];
  /** The app's own schema, generated by the same `FieldDef` the UI renders. */
  settings: FieldRead[];
  /** Advisory findings the loader published — reported, never recomputed (§3.7). */
  warnings: Diagnostic[];
  /** The settings screen's current values (`rules.json#/study`). */
  study: Record<string, unknown>;
  /** The identity washes: record id → one of the four rooms, by the plan's order. */
  washes?: Record<string, string>;
  /** The frame's context slot (R2): the plan's date, in the plan's timezone. */
  today?: TodayRead | null;
};

/**
 * The plan's own today — the one date fact the frame needs (UI_SPEC R2). The
 * engine resolves it (the plan owns the timezone) and hands the parts so no
 * screen parses an ISO string: `week` is the week record that covers today,
 * with the number of weeks beside it when the plan declares that.
 */
export type TodayRead = {
  date: string;
  day: number;
  month: string;
  weekday: string;
  week: { index: number; of: number | null } | null;
};

/**
 * One saved view as declared in `content/views.json` — the whole definition, so
 * the view editor edits the keys by name rather than rebuilding them (§4.8 P3).
 * `blocks` is `unknown[]` here on purpose: an unauthored key belongs to whatever
 * build wrote it, and the editor passes unknown keys back untouched.
 */
export type ViewDefRead = {
  /**
   * The kind this view reads — **absent on a composed screen** (COMPOSER §2.1),
   * which names widgets instead of a kind. A view must still draw something,
   * so the validator refuses one with neither `type` nor `components`.
   */
  type?: string | null;
  layout?: string | null;
  filter?: string | null;
  sort?: string | null;
  group?: string | null;
  limit?: number | null;
  columns?: string[] | null;
  nulls?: string | null;
  blocks?: Array<Record<string, unknown>> | null;
  /**
   * The screen's own composition (COMPOSER §2.1): one entry per widget, in the
   * student's order. Present — **even empty** — makes the view a composed
   * screen and takes precedence over `panel` and `blocks`; absent leaves the
   * view exactly as it was.
   *
   * `span` is the widget's width in the composed stack's two columns: `1` is
   * half, `2` is the full canvas, and an absent member means `2` (COMPOSER
   * §2.1's 2026-09-30 extension — the resize control on the frame writes it).
   */
  components?: Array<{ surface: string; span?: number }>;
  /**
   * The screen this destination is (P2): a view that declares a panel **is**
   * that screen — `today`, `reviews`, `progress` — and its blocks stay in the
   * file as the machine's own composition (D6).
   */
  panel?: string | null;
};

