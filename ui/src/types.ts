/** One group of a day's facts, by id — undefined when the read has not landed. */
export function todayGroup(facts: TodayFacts | null, id: TodayGroupId): TodayGroup | undefined {
  return facts?.groups.find((group) => group.id === id);
}

/**
 * Minutes as a student says them: `45 min`, `4 h`, `4 h 15 min`. A session
 * length is never printed as `255`.
 */
export function durationText(minutes: number): string {
  const total = Math.max(0, Math.round(minutes));
  if (total < 60) return `${total} min`;
  const hours = Math.floor(total / 60);
  const rest = total % 60;
  return rest === 0 ? `${hours} h` : `${hours} h ${rest} min`;
}

